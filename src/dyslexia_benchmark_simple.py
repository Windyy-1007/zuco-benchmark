"""
---------------------------------------------------------------
Dyslexia Prediction Benchmark - Using Pre-extracted Features
---------------------------------------------------------------

Description:
    This script performs dyslexia prediction using pre-extracted EEG and 
    eye-tracking features from the ZuCo dataset. It classifies subjects as 
    dyslexic or normal based on their neural responses during reading.

Usage:
    python dyslexia_benchmark_simple.py

Note:
    This version uses the already extracted features in the features/ directory
    and applies dyslexia labels generated by analyze_eeg_performance.py
"""

import time
from datetime import timedelta
import numpy as np
import pandas as pd
import config
import dyslexia_labels as dl
import classifier as clf
from sklearn.preprocessing import MinMaxScaler
from sklearn.decomposition import PCA
from sklearn.utils import shuffle

def load_features_with_dyslexia_labels(subjects, feature_sets):
    """
    Load pre-extracted features and apply dyslexia labels
    """
    print("Loading dyslexia labels...")
    dyslexia_labels = dl.load_dyslexia_labels()
    if dyslexia_labels is None:
        print("Warning: Using default dyslexia labels")
        dyslexia_labels = dl.get_default_dyslexia_labels()
    
    features_data = {}
    labels_data = {}
    
    for feature_set in feature_sets:
        features_data[feature_set] = {}
        labels_data[feature_set] = {}
        
        for subject in subjects:
            try:
                # Load pre-extracted features
                feature_path = f"../features/{subject}_{feature_set}.npy"
                subject_features = np.load(feature_path, allow_pickle=True).item()
                
                # Apply dyslexia labels to each sample
                subject_dyslexia_label = dyslexia_labels.get(subject, 0)
                
                features_list = []
                labels_list = []
                
                for sample_id, sample_data in subject_features.items():
                    # Extract features (all except last element which is original label)
                    features = sample_data[:-1]
                    features_list.append(features)
                    labels_list.append(subject_dyslexia_label)  # Use dyslexia label instead
                
                features_data[feature_set][subject] = features_list
                labels_data[feature_set][subject] = labels_list
                
                print(f"Loaded {len(features_list)} samples for {subject} ({feature_set}), "
                      f"label: {'Dyslexic' if subject_dyslexia_label == 1 else 'Normal'}")
                
            except FileNotFoundError:
                print(f"Warning: Feature file not found for {subject} - {feature_set}")
            except Exception as e:
                print(f"Error loading {subject} - {feature_set}: {e}")
    
    return features_data, labels_data

def prepare_output_file():
    """Create output file for results"""
    from datetime import datetime
    import os
    
    if not os.path.exists("../results"):
        os.makedirs("../results")
    
    filename = ("../results/" + 
                datetime.now().strftime("%Y%m%d-%H%M%S") + 
                "_svm_results_" + config.class_task + 
                "_" + config.dataset + 
                "_random" + str(config.randomized) + 
                "_" + config.kernel + ".csv")
    
    return open(filename, 'w')

def main():
    start = time.time()
    
    print("="*60)
    print("DYSLEXIA PREDICTION BENCHMARK")
    print("="*60)
    
    # Print dyslexia label summary
    dl.print_dyslexia_summary()
    
    # Load training data (normal subjects)
    print(f"\n1. Loading training data from {len(config.subjects)} subjects...")
    train_features, train_labels = load_features_with_dyslexia_labels(
        config.subjects, config.feature_sets)
    
    # Load test data (heldout subjects) 
    print(f"\n2. Loading test data from {len(config.heldout_subjects)} subjects...")
    test_features, test_labels = load_features_with_dyslexia_labels(
        config.heldout_subjects, config.feature_sets)
    
    # Prepare output file
    print("\n3. Preparing output files...")
    result_file = prepare_output_file()
    
    print(f"\n4. Running classification with {len(config.feature_sets)} feature sets...")
    all_results = {}
    
    for feature_set in config.feature_sets:
        print(f"\n" + "="*50)
        print(f"Processing feature set: {feature_set}")
        print("="*50)
        
        # Get training features and labels
        train_X = train_features[feature_set]
        train_y = train_labels[feature_set] 
        
        # Get test features and labels
        test_X = test_features[feature_set]
        test_y = test_labels[feature_set]
        
        print(f"Training subjects: {len(train_X)}")
        print(f"Test subjects: {len(test_X)}")
        
        # Check data balance in training set
        train_labels_flat = [label for subj_labels in train_y.values() for label in subj_labels]
        dyslexic_count = sum(1 for label in train_labels_flat if label == 1)
        normal_count = len(train_labels_flat) - dyslexic_count
        print(f"Training data balance: {dyslexic_count} dyslexic, {normal_count} normal samples")
        
        if len(train_labels_flat) == 0:
            print(f"No training data for {feature_set}, skipping...")
            continue
        
        # Apply PCA if configured and dealing with electrode features
        if config.pca_preprocessing and 'electrode' in feature_set:
            print(f"Applying PCA (explained variance: {config.explained_variance})...")
            
            # Prepare data for PCA
            all_train_X = []
            for subj_data in train_X.values():
                all_train_X.extend(subj_data)
            
            if len(all_train_X) > 0:
                pca = PCA()
                pca.fit(all_train_X)
                
                # Find number of components for desired explained variance
                cumsum = np.cumsum(pca.explained_variance_ratio_)
                n_components = np.argmax(cumsum >= config.explained_variance) + 1
                
                print(f"Using {n_components} PCA components (explains {cumsum[n_components-1]:.3f} variance)")
                
                # Apply PCA transformation
                pca_final = PCA(n_components=n_components)
                pca_final.fit(all_train_X)
                
                # Transform training data
                for subj in train_X:
                    train_X[subj] = pca_final.transform(train_X[subj]).tolist()
                
                # Transform test data
                for subj in test_X:
                    test_X[subj] = pca_final.transform(test_X[subj]).tolist()
        
        # Run classification
        print(f"Running SVM classification...")
        try:
            # Check if we have true test labels for evaluation
            test_labels_exist = any(len(labels) > 0 for labels in test_y.values())
            
            if test_labels_exist:
                # Use full benchmark with evaluation
                results = clf.benchmark(train_X, train_y, test_X, test_y)
                predictions, bootstrap_results = results[0], results[1] if len(results) > 1 else [[]]
                
                # Extract metrics
                pred_lists, accuracies, f1_scores, precisions, recalls = predictions
                
                # Print and save results
                print(f"\nResults for {feature_set}:")
                for i, subj in enumerate(config.heldout_subjects):
                    if i < len(accuracies):
                        accuracy, f1, precision, recall = accuracies[i], f1_scores[i], precisions[i], recalls[i]
                        
                        print(f"  {subj}: Acc={accuracy:.3f}, F1={f1:.3f}, P={precision:.3f}, R={recall:.3f}")
                        
                        # Save to file
                        result_file.write(f"{subj} {feature_set} accuracy {accuracy} 0.0\n")
                        result_file.write(f"{subj} {feature_set} f1 {f1} 0.0\n")
                        result_file.write(f"{subj} {feature_set} precision {precision} 0.0\n")
                        result_file.write(f"{subj} {feature_set} recall {recall} 0.0\n")
                        
                        # Store predictions for submission
                        if config.create_submission and i < len(pred_lists):
                            all_results[f"{subj}_{feature_set}"] = pred_lists[i][0]
                
                # Calculate overall performance
                overall_accuracy = np.mean(accuracies)
                overall_f1 = np.mean(f1_scores)
                print(f"  Overall: Acc={overall_accuracy:.3f}, F1={overall_f1:.3f}")
                
            else:
                # Baseline prediction without true labels
                print("Running baseline prediction (no evaluation)...")
                results = clf.benchmark_baseline(train_X, train_y, test_X, test_y)
                
                # Store predictions for submission
                if config.create_submission:
                    for i, subj in enumerate(config.heldout_subjects):
                        if i < len(results):
                            all_results[f"{subj}_{feature_set}"] = results[i]
                            print(f"  {subj}: {len(results[i])} predictions generated")
                            
        except Exception as e:
            print(f"Error in classification for {feature_set}: {e}")
            continue
    
    # Create submission files if requested
    if config.create_submission and all_results:
        print(f"\n5. Creating submission files...")
        
        # Ensure submission directory exists
        import os
        if not os.path.exists("../submissions"):
            os.makedirs("../submissions")
        
        # Save predictions as numpy file
        if config.save_prediction_npy:
            submission_path = f"../submissions/dyslexia_predictions_{config.dataset}.npy"
            np.save(submission_path, all_results)
            print(f"  Saved predictions to: {submission_path}")
        
        # Save predictions as CSV for human inspection
        submission_df = []
        for key, predictions in all_results.items():
            parts = key.split('_')
            subject = parts[0]
            feature_set = '_'.join(parts[1:])
            
            for i, pred in enumerate(predictions):
                submission_df.append({
                    'Subject': subject,
                    'Feature_Set': feature_set,
                    'Sample_Index': i,
                    'Prediction': int(pred),
                    'Prediction_Label': 'Dyslexic' if pred == 1 else 'Normal'
                })
        
        if submission_df:
            submission_df = pd.DataFrame(submission_df)
            csv_path = f"../submissions/dyslexia_predictions_{config.dataset}.csv"
            submission_df.to_csv(csv_path, index=False)
            print(f"  Saved predictions to: {csv_path}")
            
            # Summary statistics
            print(f"\n  Prediction Summary:")
            summary = submission_df.groupby(['Subject', 'Feature_Set'])['Prediction'].agg(['count', 'sum', 'mean']).round(3)
            summary.columns = ['Total_Samples', 'Dyslexic_Predictions', 'Dyslexic_Ratio']
            print(summary.head(10))  # Show first 10 rows
    
    result_file.close()
    
    elapsed = time.time() - start
    print(f"\n" + "="*60)
    print(f"DYSLEXIA PREDICTION BENCHMARK COMPLETED")
    print(f"Total runtime: {str(timedelta(seconds=elapsed))}")
    print("="*60)

if __name__ == '__main__':
    main()
